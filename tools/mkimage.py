import argparse
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'mosaic'))
from ps4elf import (Ps4Elf, PT_LOAD, PT_SCE_RELRO, PT_SCE_PROCPARAM, PT_TLS, DT_INIT, DT_FINI,
                    DT_INIT_ARRAY, DT_INIT_ARRAYSZ, DT_PREINIT_ARRAY, DT_PREINIT_ARRAYSZ,
                    R_X86_64_RELATIVE, R_X86_64_JUMP_SLOT, R_X86_64_GLOB_DAT, R_X86_64_64, R_X86_64_DTPMOD64)

STT_OBJECT, STT_FUNC = 1, 2

def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('eboot')
    ap.add_argument('out')
    ap.add_argument('--prefix', default='og')
    ap.add_argument('--name', default='eboot')
    a = ap.parse_args()
    e = Ps4Elf(a.eboot)
    P = a.prefix
    os.makedirs(a.out, exist_ok=True)

    segs, blob = [], bytearray()
    for i, p in enumerate(e.ph):
        if p[0] not in (PT_LOAD, PT_SCE_RELRO):
            continue
        data = e.segs.get(i, b'')[:p[5]]
        segs.append((p[3], p[6], len(data), len(blob), p[1]))
        blob += data
        blob += bytes(-len(blob) % 16)
    image_size = max(v + m for v, m, _, _, _ in segs)
    image_size = (image_size + 0xFFFF) & ~0xFFFF
    open(os.path.join(a.out, 'og_image.bin'), 'wb').write(blob)

    relative, other, tlsmod = [], [], []
    for off, rtype, sym, addend in e.relocs + e.plt_relocs:
        s = e.symbols[sym] if sym else None
        if rtype == R_X86_64_RELATIVE:
            relative.append((off, addend))
        elif rtype == R_X86_64_DTPMOD64:
            tlsmod.append(off)
        elif s is not None and s['value'] != 0 and rtype in (R_X86_64_64, R_X86_64_GLOB_DAT, R_X86_64_JUMP_SLOT):
            relative.append((off, s['value'] + (addend if rtype == R_X86_64_64 else 0)))
        else:
            other.append((off, rtype, sym, addend))

    imports, index = [], {}
    slots = []
    for off, rtype, sym, addend in other:
        s = e.symbols[sym]
        if s['library'] is None:
            sys.exit(f'relocation {rtype} at {off:#x} to {s["raw"]!r}: not handled')
        key = (s['name'] or s['nid'], s['library'])
        if key not in index:
            index[key] = len(imports)
            imports.append((s['name'] or s['nid'], s['library'], s['nid'], 'data' if s['type'] == STT_OBJECT else 'func'))
        kind = {R_X86_64_JUMP_SLOT: 'OG_SLOT_FUNC', R_X86_64_GLOB_DAT: 'OG_SLOT_ADDR',
                R_X86_64_64: 'OG_SLOT_ADDR'}.get(rtype)
        if kind is None:
            sys.exit(f'relocation type {rtype} at {off:#x}: not handled')
        slots.append((off, index[key], kind, addend if rtype == R_X86_64_64 else 0))

    exports, seen = [], set()
    for s in e.symbols:
        if s['value'] and s['library'] and s['bind'] in (1, 2):
            name = s['name'] or s['nid']
            if name not in seen:
                seen.add(name)
                exports.append((name, s['value'], 1 if s['type'] == STT_OBJECT else 0))
    exports.sort(key=lambda x: x[0])

    slot_import = {off: i for off, i, _, _ in slots}
    plt = sorted((stub, slot_import[slot]) for stub, slot in e.plt_stubs().items() if slot in slot_import)
    procparam = next((p[3] for p in e.ph if p[0] == PT_SCE_PROCPARAM), 0)
    tls = next(((p[3], p[5], p[6], p[7]) for p in e.ph if p[0] == PT_TLS), (0, 0, 0, 1))

    rel_at = dict(relative)

    def array_of(tag, size_tag):
        if not e.dyn.get(tag) or not e.dyn.get(size_tag):
            return []
        return [rel_at.get(e.dyn[tag] + 8 * k, 0) for k in range(e.dyn[size_tag] // 8)]
    init = array_of(DT_PREINIT_ARRAY, DT_PREINIT_ARRAYSZ) + array_of(DT_INIT_ARRAY, DT_INIT_ARRAYSZ)

    bin_path = os.path.abspath(os.path.join(a.out, 'og_image.bin'))
    L = ['/* generated by tools/mkimage.py from the title\'s files: do not edit, do not share */',
         '#include "image.h"', '',
         f'__asm__(".section .rodata\\n.balign 16\\n{P}_image_bytes:\\n'
         f'.incbin \\"{bin_path}\\"\\n.previous");',
         f'extern const uint8_t {P}_image_bytes[] __asm__("{P}_image_bytes");', '',
         'static const OgSegment segments[] = {']
    L += [f'    {{0x{v:X}ull, 0x{m:X}ull, 0x{f:X}u, 0x{o:X}u, {fl}}},' for v, m, f, o, fl in segs]
    L += ['};', 'static const OgRelative relative[] = {']
    L += [f'    {{0x{o:X}ull, {"-" if a_ < 0 else ""}0x{abs(a_):X}ll}},' for o, a_ in relative]
    L += ['    {0, 0}', '};', 'static const OgImport imports[] = {']
    L += [f'    {{{c_str(n)}, {c_str(lib)}, {c_str(nid)}, {1 if k == "data" else 0}}},' for n, lib, nid, k in imports]
    L += ['    {0, 0, 0, 0}', '};', 'static const OgSlot slots[] = {']
    L += [f'    {{0x{o:X}ull, {i}, {k}, {a_}ll}},' for o, i, k, a_ in slots]
    L += ['    {0, 0, 0, 0}', '};', 'static const OgPlt plt[] = {']
    L += [f'    {{0x{s:X}ull, {i}}},' for s, i in plt]
    L += ['    {0, 0}', '};', 'static const OgExport exports[] = {']
    L += [f'    {{{c_str(n)}, 0x{v:X}ull, {d}}},' for n, v, d in exports]
    L += ['    {0, 0, 0}', '};', 'static const uint64_t tls_module_slots[] = {']
    L += [f'    0x{o:X}ull,' for o in tlsmod]
    L += ['    0', '};', 'static const uint64_t init_array[] = {']
    L += [f'    0x{v:X}ull,' for v in init]
    L += ['    0', '};', '',
          f'const void* {P}_entries(const void* host, unsigned* count);', '',
          f'const OgModule {P}_module = {{',
          f'    {c_str(a.name)}, {P}_image_bytes, 0x{image_size:X}ull,',
          f'    0x{e.entry:X}ull, 0x{e.dyn.get(DT_INIT, 0):X}ull, 0x{e.dyn.get(DT_FINI, 0):X}ull, 0x{procparam:X}ull,',
          f'    {{0x{tls[0]:X}ull, 0x{tls[1]:X}ull, 0x{tls[2]:X}ull, 0x{tls[3]:X}ull}},',
          f'    {len(segs)}, segments, {len(relative)}, relative, {len(imports)}, imports, {len(slots)}, slots,',
          f'    {len(plt)}, plt, {len(exports)}, exports, {len(tlsmod)}, tls_module_slots, {len(init)}, init_array,',
          f'    {P}_entries,',
          '};', '']
    open(os.path.join(a.out, 'og_image.c'), 'w', newline='\n').write('\n'.join(L))
    print(f'{a.name}: image 0x{image_size:X} bytes ({len(blob)} from the file), {len(segs)} segments, '
          f'{len(relative)} relative relocations, {len(imports)} imports in {len(slots)} slots, '
          f'{len(plt)} PLT stubs, {len(exports)} exports, {len(tlsmod)} TLS module slots, '
          f'{len(init)} init functions')

if __name__ == '__main__':
    main()
